# Aion Forge icon: a two-armed logarithmic spiral galaxy on the app's void colour.
# Run from this folder: python3 make_icon.py. Copy foreground.xml to
# app/src/main/res/drawable/ic_launcher_foreground.xml and icon.svg to
# ../../public/favicon.svg. Legacy mipmap PNGs were rendered from the centre
# 72 units of icon.svg (headless Chrome, then resized per density).
# Writes icon.svg (108-unit canvas, adaptive-icon geometry) and foreground.xml (VectorDrawable).
import math
C = 54.0                      # centre of the 108 x 108 adaptive canvas
B = 0.36                      # spiral pitch: r = A * e^(B*t)
A = 4.6
T_END = 1.75 * math.pi        # how far each arm winds
STEPS = 90

def arm(phase, width0, width1):
    inner, outer = [], []
    for i in range(STEPS + 1):
        t = T_END * i / STEPS
        r = A * math.exp(B * t)
        ang = t + phase
        x, y = C + r * math.cos(ang), C + r * math.sin(ang)
        # tangent of the log spiral, then the normal
        dx = B * math.cos(ang) - math.sin(ang)
        dy = B * math.sin(ang) + math.cos(ang)
        n = math.hypot(dx, dy); nx, ny = -dy / n, dx / n
        f = i / STEPS
        w = width0 * (1 - f) ** 0.9 + width1 * f
        inner.append((x + nx * w, y + ny * w)); outer.append((x - nx * w, y - ny * w))
    pts = inner + outer[::-1]
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + " Z"

arms = [arm(0, 3.6, 0.25), arm(math.pi, 3.6, 0.25)]
stars = [(31.5, 32.5, 1.1), (80.5, 68.0, 0.9), (68.0, 83.0, 0.7)]
ARM = "#C9D6EA"; CORE = "#F2C98A"; GLOW = "#E0A458"; BG = "#07080A"

svg = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="108" height="108">',
       '<defs><radialGradient id="g" cx="54" cy="54" r="26" gradientUnits="userSpaceOnUse">'
       f'<stop offset="0" stop-color="{GLOW}" stop-opacity="0.55"/><stop offset="1" stop-color="{GLOW}" stop-opacity="0"/></radialGradient></defs>',
       f'<rect width="108" height="108" fill="{BG}"/>',
       '<circle cx="54" cy="54" r="26" fill="url(#g)"/>']
svg += [f'<path d="{d}" fill="{ARM}" fill-opacity="0.92"/>' for d in arms]
svg += [f'<circle cx="54" cy="54" r="6.2" fill="{CORE}"/>']
svg += [f'<circle cx="{x}" cy="{y}" r="{r}" fill="#E8EAED"/>' for x, y, r in stars]
svg.append('</svg>')
open("icon.svg", "w").write("\n".join(svg))

def circle(cx, cy, r):
    return f"M{cx - r:.2f},{cy:.2f} a{r},{r} 0 1,0 {2*r:.2f},0 a{r},{r} 0 1,0 {-2*r:.2f},0 Z"

vd = ['<?xml version="1.0" encoding="utf-8"?>',
      '<!-- Aion Forge launcher icon foreground: a two-armed spiral galaxy (generated by android/icon/make_icon.py) -->',
      '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"',
      '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">',
      f'    <path android:pathData="{circle(54, 54, 26)}">',
      '        <aapt:attr name="android:fillColor">',
      '            <gradient android:type="radial" android:centerX="54" android:centerY="54" android:gradientRadius="26">',
      '                <item android:offset="0" android:color="#8CE0A458"/>',
      '                <item android:offset="1" android:color="#00E0A458"/>',
      '            </gradient>',
      '        </aapt:attr>',
      '    </path>']
vd += [f'    <path android:fillColor="#EB{ARM[1:]}" android:pathData="{d}"/>' for d in arms]
vd += [f'    <path android:fillColor="{CORE}" android:pathData="{circle(54, 54, 6.2)}"/>']
vd += [f'    <path android:fillColor="#E8EAED" android:pathData="{circle(x, y, r)}"/>' for x, y, r in stars]
vd.append('</vector>')
open("foreground.xml", "w").write("\n".join(vd) + "\n")
